import { pathToFileURL } from 'node:url';
import { config, ensure, fields, issueNumber, workBranch, validateVersions, setVersion,
  reviewBody, nextSnapshot, isMonthEndAden, releaseNotes, updateChangelog, changelogEntry,
  verifyRun, tagAction, parseVersion } from './core.mjs';
import { GitHub } from './github.mjs';
import { checkPR, releaseContext } from './policy.mjs';

const repoOwner = config.repository.split('/')[0];
const hasLabel = (issue, label) => issue.labels.some(item => (item.name ?? item) === label);
const issueBody = metadata => Object.entries(metadata).map(([key, value]) => `${key}: ${value}`).join('\n') +
  '\nReview the preparation and promotion PRs before publishing. The Issue closes after verified synchronization.\n';

async function openPR(api, branch, base) {
  return (await api.list(`pulls?state=open&base=${base}&head=${encodeURIComponent(`${repoOwner}:${branch}`)}`))[0];
}

async function ensurePR(api, { branch, base, title, body, issue }) {
  let pr = await openPR(api, branch, base);
  let changed = false;
  if (!pr) {
    pr = await api.write('POST', 'pulls', { head: branch, base, title, body, draft: false });
    changed = true;
  } else {
    ensure(issueNumber(pr.body) === issue, 'An existing PR belongs to another Issue; do not overwrite it.');
    const old = fields(pr.body), fresh = fields(body);
    if (old['Reviewed-Head'] !== pr.head.sha &&
        (old['Release-Source'] !== fresh['Release-Source'] || old['Release-Version'] !== fresh['Release-Version'])) {
      pr = await api.write('PATCH', `pulls/${pr.number}`, { title, body });
      changed = true;
    }
  }
  if (changed) {
    await api.commentOnce(issue, `<!-- rain-erp:pr:${pr.number} -->`,
      `Review required: ${pr.html_url}. Record the reviewed head and validation results in its body.`);
  }
  // Explicit dispatch avoids relying on recursive events generated by GITHUB_TOKEN.
  await api.dispatch(pr);
  return pr;
}

export async function prepare(api, { dryRun = false, scheduled = false, requested, date = new Date() } = {}) {
  if (scheduled && !isMonthEndAden(date)) return { action: 'skip', reason: 'Not month end in Asia/Aden.' };
  const pending = (await api.list('issues?state=open&labels=kind%3Arelease')).filter(item => !item.pull_request);
  ensure(pending.length <= 1, 'More than one release Issue is active; reconcile them first.');
  let issue = pending[0];
  const previous = fields(issue?.body);
  if (previous['Release-Phase'] === 'published') return { action: 'waiting-for-synchronization', issue: issue.number };
  const source = (await api.branch(config.integrationBranch)).commit.sha;
  const explicit = requested || (previous['Release-Requested-Version'] === 'auto' ? undefined : previous['Release-Requested-Version']);
  const context = await releaseContext(api, source, explicit);
  const version = context.expectedVersion;
  if (!version) return { action: 'skip', reason: 'No unpublished changes.' };
  const sourceFiles = await api.files(source);
  const revision = validateVersions(sourceFiles);
  ensure(!await api.tagCommit(`v${version}`), 'The proposed version tag already exists; reconcile it before preparing another request.');
  const plan = { action: 'prepare-release', version: `v${version}`, source, issue: issue?.number ?? null };
  if (issue && previous['Release-Generated-Head'] && revision === version &&
      changelogEntry(sourceFiles['CHANGELOG.md'] ?? '', version) === releaseNotes(version, context.commits, issue.number).trim()) {
    return { ...plan, action: previous['Release-Phase'] === 'promotion' ? 'waiting-for-promotion' : 'waiting-for-verification' };
  }
  if (dryRun) return plan;

  if (!issue) {
    issue = await api.write('POST', 'issues', {
      title: `Release v${version}`, labels: ['kind:release'],
      body: issueBody({ 'Release-Version': `v${version}`, 'Release-Source': source,
        'Release-Phase': 'prepare', 'Release-Requested-Version': explicit || 'auto' })
    });
  }
  const branch = `chore/${issue.number}-prepare-release`;
  let ref = await api.get(`git/ref/heads/${branch}`, { optional: true });
  if (!ref) {
    ref = await api.write('POST', 'git/refs', { ref: `refs/heads/${branch}`, sha: source });
  }
  const head = ref.object.sha;
  if (head !== source && previous['Release-Generated-Head']) {
    ensure(head === previous['Release-Generated-Head'], 'Release branch contains manual changes; do not overwrite them.');
  } else if (head !== source) {
    throw new Error('An existing release branch needs manual reconciliation before automation can update it.');
  }
  const notes = releaseNotes(version, context.commits, issue.number);
  const files = Object.fromEntries(config.versionFiles.map(path => [path, setVersion(path, sourceFiles[path], version)]));
  let changelog = sourceFiles['CHANGELOG.md'] ?? '# Changelog\n\n## [Unreleased]\n\n';
  const oldVersion = previous['Release-Version']?.slice(1);
  if (oldVersion && oldVersion !== version && context.latest?.tag_name !== `v${oldVersion}`) {
    const escaped = oldVersion.replaceAll('.', '\\.');
    changelog = changelog.replace(new RegExp(`^## \\[${escaped}\\][^\\n]*\\n[\\s\\S]*?(?=^## \\[|$(?![\\s\\S]))`, 'gm'), '');
  }
  files['CHANGELOG.md'] = updateChangelog(changelog, version, notes);
  let generated = head;
  if (source !== previous['Release-Source'] || previous['Release-Version'] !== `v${version}` || !previous['Release-Generated-Head']) {
    generated = await api.commitFiles(branch, head, files,
      `chore(release): prepare v${version}\n\nIssue: #${issue.number}`, head === source ? undefined : source);
  }
  await api.write('PATCH', `issues/${issue.number}`, {
    title: `Release v${version}`,
    body: issueBody({ 'Release-Version': `v${version}`, 'Release-Source': source,
      'Release-Phase': 'prepare', 'Release-Requested-Version': explicit || 'auto', 'Release-Generated-Head': generated })
  });
  const pr = await ensurePR(api, { branch, base: config.integrationBranch,
    title: `chore(release): prepare v${version}`, issue: issue.number,
    body: reviewBody({ issue: issue.number, kind: 'release', extra: {
      'Release-Version': `v${version}`, 'Release-Source': source } }) });
  return { ...plan, issue: issue.number, pr: pr.number, head: generated };
}

async function deleteWorkBranch(api, pr) {
  if (pr.head.repo?.full_name !== config.repository || !workBranch.test(pr.head.ref)) return;
  const ref = await api.get(`git/ref/heads/${pr.head.ref}`, { optional: true });
  if (ref?.object.sha === pr.head.sha) await api.write('DELETE', `git/refs/heads/${pr.head.ref}`);
}

async function closeDelivered(api, issue, pr, run) {
  const firstDelivery = await api.commentOnce(issue.number, `<!-- rain-erp:delivered:${pr.number} -->`,
    `Delivered by ${pr.html_url}. Verified on develop at ${run.head_sha}: ${run.html_url}.`);
  if (issue.state === 'open') await api.write('PATCH', `issues/${issue.number}`, { state: 'closed', state_reason: 'completed' });
  await deleteWorkBranch(api, pr);
  return firstDelivery;
}

async function ensurePromotion(api, issue, source) {
  const version = fields(issue.body)['Release-Version'];
  const files = await api.files(source);
  ensure(`v${validateVersions(files)}` === version, 'Refresh release preparation before promotion.');
  const pr = await ensurePR(api, {
    branch: config.integrationBranch, base: config.stableBranch,
    title: `chore(release): promote ${version}`, issue: issue.number,
    body: reviewBody({ issue: issue.number, kind: 'promotion', extra: { 'Release-Version': version, 'Release-Source': source } })
  });
  await api.write('PATCH', `issues/${issue.number}`, {
    body: issueBody({ ...fields(issue.body), 'Release-Phase': 'promotion' })
  });
  return pr;
}

async function ensureSync(api, issue, publishedCommit, version) {
  const branch = `chore/${issue.number}-sync-main`;
  const existing = await openPR(api, branch, config.integrationBranch);
  if (existing) return existing;
  const completed = (await api.list(`pulls?state=closed&base=${config.integrationBranch}&head=${encodeURIComponent(`${repoOwner}:${branch}`)}`))
    .find(pr => pr.merged_at);
  if (completed) return completed;
  const source = (await api.branch(config.integrationBranch)).commit.sha;
  let ref = await api.get(`git/ref/heads/${branch}`, { optional: true });
  if (!ref) ref = await api.write('POST', 'git/refs', { ref: `refs/heads/${branch}`, sha: source });
  const previous = fields(issue.body);
  if (ref.object.sha !== source && previous['Sync-Generated-Head']) {
    ensure(ref.object.sha === previous['Sync-Generated-Head'], 'Synchronization branch contains manual changes.');
  } else if (ref.object.sha !== source) {
    throw new Error('An existing synchronization branch needs manual reconciliation.');
  }
  if (!await api.contains(publishedCommit, ref.object.sha)) {
    await api.write('POST', 'merges', { base: branch, head: publishedCommit,
      commit_message: `chore(sync): merge main after v${version}` });
  }
  const merged = (await api.branch(branch)).commit.sha;
  const contents = await api.files(merged);
  const snapshot = nextSnapshot(version);
  const files = Object.fromEntries(config.versionFiles.map(path => [path, setVersion(path, contents[path], snapshot)]));
  let generated = merged;
  if (validateVersions(contents) !== snapshot) {
    generated = await api.commitFiles(branch, merged, files,
      `chore(sync): resume ${snapshot}\n\nIssue: #${issue.number}`);
  }
  await api.write('PATCH', `issues/${issue.number}`, {
    body: issueBody({ ...previous, 'Release-Phase': 'published', 'Release-Commit': publishedCommit, 'Sync-Generated-Head': generated })
  });
  return ensurePR(api, { branch, base: config.integrationBranch,
    title: `chore(sync): resume development after v${version}`, issue: issue.number,
    body: reviewBody({ issue: issue.number, kind: 'sync', extra: { 'Release-Version': `v${version}`, 'Release-Source': publishedCommit } }) });
}

async function publish(api, run, pr, issue, dryRun) {
  const meta = fields(pr.body), issueMeta = fields(issue.body);
  const files = await api.files(run.head_sha);
  const version = validateVersions(files), tag = `v${version}`;
  ensure(meta['Release-Version'] === tag && issueMeta['Release-Version'] === tag, 'Release metadata differs from main.');
  const commit = await api.get(`git/commits/${run.head_sha}`);
  const source = await api.get(`git/commits/${pr.head.sha}`);
  ensure(commit.parents.length === 2 && commit.parents[1].sha === pr.head.sha && commit.tree.sha === source.tree.sha,
    'Release promotion must preserve the reviewed develop tree with a merge commit.');
  ensure(meta['Release-Source'] === pr.head.sha && meta['Reviewed-Head'] === pr.head.sha, 'The release candidate was not reviewed.');
  const existing = await api.get(`releases/tags/${tag}`, { optional: true });
  const existingCommit = await api.tagCommit(tag);
  const action = tagAction(existingCommit, run.head_sha);
  const notes = changelogEntry(files['CHANGELOG.md'] ?? '', version);
  ensure(notes, 'Missing release notes in the tagged source.');
  if (!existing || existing.draft) {
    // Re-evaluate against the pre-promotion main parent, not the current main tip.
    await checkPR(api, { ...pr, base: { ...pr.base, sha: commit.parents[0].sha } }, files);
  } else ensure(existingCommit === run.head_sha, 'Existing release does not match verified main.');
  const plan = { action: 'publish-release', version: tag, commit: run.head_sha, tagAction: action, existingRelease: existing?.id ?? null };
  if (issue.state === 'closed') {
    ensure(existing && !existing.draft && await api.contains(run.head_sha, (await api.branch(config.integrationBranch)).commit.sha),
      'Closed release tracking lacks a published, synchronized release.');
    return { ...plan, action: 'already-published-and-synchronized' };
  }
  if (dryRun) return plan;
  if (action === 'create') {
    const object = await api.write('POST', 'git/tags', { tag, message: `Rain-erp ${tag}`,
      object: run.head_sha, type: 'commit' });
    await api.write('POST', 'git/refs', { ref: `refs/tags/${tag}`, sha: object.sha });
  }
  const release = { tag_name: tag, target_commitish: run.head_sha, name: `Rain-erp ${tag}`,
    body: notes, prerelease: parseVersion(version)[0] === 0, draft: false,
    make_latest: parseVersion(version)[0] === 0 ? 'false' : 'true' };
  if (!existing) await api.write('POST', 'releases', release);
  else if (existing.draft) await api.write('PATCH', `releases/${existing.id}`, release);
  await api.write('PATCH', `issues/${issue.number}`, {
    body: issueBody({ ...issueMeta, 'Release-Phase': 'published', 'Release-Commit': run.head_sha })
  });
  const updated = await api.get(`issues/${issue.number}`);
  const sync = await ensureSync(api, updated, run.head_sha, version);
  return { ...plan, synchronizationPR: sync.number };
}

export async function reconcile(api, runId, { dryRun = false } = {}) {
  ensure(/^[1-9][0-9]*$/.test(String(runId)), 'A workflow run ID is required.');
  const run = await api.get(`actions/runs/${runId}`);
  ensure([config.integrationBranch, config.stableBranch].includes(run.head_branch), 'Unexpected integration branch.');
  const branch = await api.branch(run.head_branch);
  const jobs = await api.list(`actions/runs/${runId}/jobs`, 'jobs');
  verifyRun(run, jobs, run.head_branch, branch.commit.sha);
  const pulls = await api.list(`pulls?state=closed&base=${run.head_branch}&sort=updated&direction=desc`);
  const results = [];
  let milestone = false;
  for (const summary of pulls) {
    if (!summary.merged_at || !await api.contains(summary.merge_commit_sha, run.head_sha)) continue;
    const pr = await api.get(`pulls/${summary.number}`);
    const kind = fields(pr.body).Workflow;
    if (!['development', 'release', 'promotion', 'sync'].includes(kind)) continue;
    const issue = await api.get(`issues/${issueNumber(pr.body)}`);
    ensure(pr.head.repo?.full_name === config.repository && pr.base.ref === run.head_branch,
      'Merged PR repository or base differs from the verified delivery.');
    if (run.head_branch === config.stableBranch) {
      if (kind === 'promotion' && pr.merge_commit_sha === run.head_sha) results.push(await publish(api, run, pr, issue, dryRun));
      continue;
    }
    const work = workBranch.exec(pr.head.ref);
    ensure(work && Number(work[1]) === issue.number && !issue.pull_request,
      'Merged PR Issue differs from its numbered work branch.');
    const deliveryCommit = await api.get(`git/commits/${pr.merge_commit_sha}`);
    ensure(deliveryCommit.parents.length === (kind === 'sync' ? 2 : 1),
      'Use squash for development/preparation and merge commits for synchronization.');
    if (kind === 'development') {
      ensure(!hasLabel(issue, 'kind:release'), 'Development delivery cannot close a release Issue.');
      const delivered = dryRun ? issue.state === 'open' : await closeDelivered(api, issue, pr, run);
      results.push({ action: 'close-development-issue', issue: issue.number, pr: pr.number, commit: run.head_sha });
      // Only a newly delivered milestone starts preparation; reruns do not create empty cycles.
      if (delivered && hasLabel(issue, 'release:milestone')) milestone = true;
    } else if (issue.state === 'open' && kind === 'release' && fields(issue.body)['Release-Phase'] !== 'published') {
      if (!dryRun) { await ensurePromotion(api, issue, run.head_sha); await deleteWorkBranch(api, pr); }
      results.push({ action: 'prepare-promotion', issue: issue.number, commit: run.head_sha });
    } else if (issue.state === 'open' && kind === 'sync') {
      const meta = fields(issue.body);
      ensure(meta['Release-Phase'] === 'published' && await api.contains(meta['Release-Commit'], run.head_sha), 'The synchronized release is not present.');
      ensure(validateVersions(await api.files(run.head_sha)) === nextSnapshot(meta['Release-Version'].slice(1)), 'Next development version is missing.');
      if (!dryRun) await closeDelivered(api, issue, pr, run);
      results.push({ action: 'complete-release', issue: issue.number, commit: run.head_sha });
    }
  }
  if (milestone) results.push(await prepare(api, { dryRun }));
  return { branch: run.head_branch, commit: run.head_sha, dryRun, results };
}

async function main() {
  ensure(!process.env.GITHUB_REPOSITORY || process.env.GITHUB_REPOSITORY === config.repository, 'Unexpected repository.');
  const [command, ...args] = process.argv.slice(2);
  const allowed = command === 'prepare' ? ['--dry-run', '--scheduled', '--version'] : ['--dry-run', '--run-id'];
  for (let index = 0; index < args.length; index++) {
    ensure(allowed.includes(args[index]), `Unknown argument: ${args[index]}`);
    if (['--version', '--run-id'].includes(args[index])) {
      ensure(args[index + 1] && !args[index + 1].startsWith('--'), `Missing value for ${args[index]}`);
      index++;
    }
  }
  const dryRun = args.includes('--dry-run');
  const option = name => args.includes(name) ? args[args.indexOf(name) + 1] : undefined;
  const api = new GitHub();
  const result = command === 'prepare'
    ? await prepare(api, { dryRun, scheduled: args.includes('--scheduled'), requested: option('--version') })
    : command === 'reconcile'
      ? await reconcile(api, option('--run-id'), { dryRun })
      : (() => { throw new Error('Use prepare or reconcile; publication requires verified main CI.'); })();
  console.log(JSON.stringify(result, null, 2));
}

